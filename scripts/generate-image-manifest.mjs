// images/ 配下の全画像を走査し、内容ハッシュ(短縮)のマニフェストを生成する。
// 出力: src/imagesManifest.generated.js
//
// アプリは imageUrl.js 経由で URL に ?v=<hash> を付与してキャッシュバスティングする。
// ファイルが書き換わったエントリだけハッシュが変わり、変更画像のみ再取得される。

import { createHash } from 'node:crypto';
import { readFile, readdir, stat, writeFile } from 'node:fs/promises';
import { dirname, join, posix, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(here, '..');
const imagesDir = resolve(projectRoot, 'images');
const outFile = resolve(projectRoot, 'src', 'imagesManifest.generated.js');

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...(await walk(full)));
    } else if (entry.isFile()) {
      files.push(full);
    }
  }
  return files;
}

async function hashFile(path) {
  const buf = await readFile(path);
  return createHash('sha1').update(buf).digest('hex').slice(0, 8);
}

async function main() {
  try {
    await stat(imagesDir);
  } catch {
    // images/ が無い環境(CIの一部など)では空マニフェストを出す
    await writeFile(outFile, emit({}));
    return;
  }

  const files = await walk(imagesDir);
  const manifest = {};
  await Promise.all(
    files.map(async (file) => {
      const rel = relative(imagesDir, file).split(/[\\/]/).join(posix.sep);
      manifest[rel] = await hashFile(file);
    }),
  );

  // キー順を安定させて差分を最小化
  const sorted = Object.fromEntries(
    Object.keys(manifest).sort().map((k) => [k, manifest[k]]),
  );

  await writeFile(outFile, emit(sorted));
  console.log(`[images-manifest] ${files.length} files -> ${relative(projectRoot, outFile)}`);
}

function emit(obj) {
  return `// Auto-generated by scripts/generate-image-manifest.mjs. Do not edit.\nexport default ${JSON.stringify(obj, null, 2)};\n`;
}

main().catch((err) => {
  console.error('[images-manifest] failed:', err);
  process.exit(1);
});
